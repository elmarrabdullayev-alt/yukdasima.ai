/**
 * Returns geographic neighbors for a given destination slug
 */
export function getGeographicNeighbors(slug: string): RegionalDestination[] {
  const dest = REGIONAL_DESTINATIONS[slug];
  if (!dest) return [];

  return dest.neighborSlugs
    .map((neighborSlug) => REGIONAL_DESTINATIONS[neighborSlug])
    .filter((n): n is RegionalDestination => !!n);
}

/**
 * Returns economic region group for a given destination slug
 */
export function getEconomicRegionGroup(slug: string): EconomicRegionGroup | undefined {
  return ECONOMIC_REGION_GROUPS.find((group) => group.destinationSlugs.includes(slug));
}
